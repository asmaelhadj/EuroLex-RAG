"""Generate *candidate* questions with an LLM. Every row is written as pending and must be
reviewed by a human (review_cli) before it can be used for metrics.

    python -m eurolex.evaluation.candidates --model mistral:latest --articles 30
"""

import argparse
import json
import logging
import random
import sys
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path

from eurolex.config import get_settings
from eurolex.evaluation.questions import (
    QUESTIONS_PATH,
    load_articles,
    load_questions,
    next_id,
    normalise,
    save_questions,
)
from eurolex.generation.llm import LLMClient, LLMError, OllamaClient
from eurolex.schemas import Article, Question

logger = logging.getLogger(__name__)

MAX_ARTICLE_CHARS = 6000
SINGLE_TYPES = ["factual", "definition", "obligation", "paraphrase"]

SYSTEM = (
    "You write test questions for a search engine over the EU General Data Protection "
    "Regulation (GDPR). The questions must sound like real people: employees, small business "
    "owners, customers. Write plain everyday English. Do not copy phrases from the legal text, "
    "do not mention article numbers, and do not answer the questions."
)


def _schema(types: Sequence[str]) -> dict[str, object]:
    return {
        "type": "object",
        "properties": {
            "questions": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "question": {"type": "string"},
                        "type": {"type": "string", "enum": list(types)},
                    },
                    "required": ["question", "type"],
                },
            }
        },
        "required": ["questions"],
    }


def _article_block(article: Article) -> str:
    text = article.text[:MAX_ARTICLE_CHARS]
    return f"Article {article.article_number} - {article.title}\n{text}"


@dataclass(frozen=True)
class Draft:
    question: str
    type: str
    gold: list[str]
    notes: str


def parse_reply(raw: str, allowed_types: Sequence[str], limit: int) -> list[tuple[str, str]]:
    """Pull (question, type) pairs out of the model's JSON; anything malformed is skipped."""
    try:
        items = json.loads(raw).get("questions", [])
    except (ValueError, AttributeError):
        return []
    out: list[tuple[str, str]] = []
    for item in items if isinstance(items, list) else []:
        if not isinstance(item, dict):
            continue
        text = str(item.get("question", "")).strip()
        qtype = str(item.get("type", "")).strip()
        if len(text) >= 10 and qtype in allowed_types:
            out.append((text, qtype))
    return out[:limit]


class CandidateGenerator:
    def __init__(self, llm: LLMClient, temperature: float = 0.7) -> None:
        self._llm = llm
        self._temperature = temperature

    def _ask(self, prompt: str, types: Sequence[str], limit: int) -> list[tuple[str, str]]:
        try:
            raw = self._llm.generate(
                prompt, system=SYSTEM, json_schema=_schema(types), temperature=self._temperature
            )
        except LLMError as exc:
            logger.warning("generation failed: %s", exc)
            return []
        return parse_reply(raw, types, limit)

    def _note(self, kind: str, sources: Iterable[str]) -> str:
        return f"generated by {self._llm.model} ({kind}) from {', '.join(sources)}"

    def single(self, article: Article, n: int) -> list[Draft]:
        prompt = (
            f"Write {n} different questions that this article answers. Use a mix of these "
            f"types: {', '.join(SINGLE_TYPES)}. 'paraphrase' means the question uses none of "
            f"the article's key terms.\n\n{_article_block(article)}"
        )
        return [
            Draft(text, qtype, [article.article_id], self._note("single", [article.article_id]))
            for text, qtype in self._ask(prompt, SINGLE_TYPES, n)
        ]

    def false_premise(self, article: Article) -> list[Draft]:
        prompt = (
            "Write 1 question that is based on a common misunderstanding which this article "
            "corrects. The question should take the wrong belief for granted.\n\n"
            f"{_article_block(article)}"
        )
        return [
            Draft(
                text, qtype, [article.article_id], self._note("false premise", [article.article_id])
            )
            for text, qtype in self._ask(prompt, ["factual"], 1)
        ]

    def multi(self, first: Article, second: Article) -> list[Draft]:
        prompt = (
            "Write 1 question that can only be answered fully by combining BOTH articles below."
            f"\n\n{_article_block(first)}\n\n{_article_block(second)}"
        )
        gold = [first.article_id, second.article_id]
        return [
            Draft(text, qtype, gold, self._note("multi article", gold))
            for text, qtype in self._ask(prompt, ["multi_article"], 1)
        ]

    def out_of_scope(self, n: int) -> list[Draft]:
        # near misses: they sound like privacy questions, so refusing them is not trivial
        prompt = (
            f"Write {n} questions that sound like data protection or privacy questions but "
            "that the GDPR itself does NOT answer. Draw on topics such as: the EU AI Act, "
            "cookie banner rules under the ePrivacy Directive, US or Californian privacy law, "
            "the UK ICO registration fee, national employment or tax law, consumer contract "
            "rules, copyright. Do not ask how the GDPR applies to something. Vary them."
        )
        return [
            Draft(text, qtype, [], self._note("out of scope", ["no article"]))
            for text, qtype in self._ask(prompt, ["out_of_scope"], n)
        ]


def reference_pairs(articles: dict[str, Article]) -> list[tuple[Article, Article]]:
    """Article pairs linked by a cross-reference in the text, e.g. Art. 17 -> Art. 6."""
    pairs: dict[tuple[str, str], tuple[Article, Article]] = {}
    for article in articles.values():
        for ref in article.references:
            target = articles.get(f"{article.act_id}:art-{ref.article_number}")
            if target is not None and target.article_id != article.article_id:
                pairs[(article.article_id, target.article_id)] = (article, target)
    return [pairs[key] for key in sorted(pairs)]


def build_candidates(
    generator: CandidateGenerator,
    articles: dict[str, Article],
    *,
    n_articles: int,
    per_article: int,
    n_false_premise: int,
    n_multi: int,
    n_oos: int,
    seed: int,
) -> list[Draft]:
    rng = random.Random(seed)  # noqa: S311  (sampling, not security)
    pool = sorted(articles.values(), key=lambda a: a.article_id)
    chosen = rng.sample(pool, min(n_articles, len(pool)))
    drafts: list[Draft] = []
    for i, article in enumerate(chosen, start=1):
        logger.info("article %d/%d: %s", i, len(chosen), article.article_id)
        drafts += generator.single(article, per_article)
    for article in rng.sample(pool, min(n_false_premise, len(pool))):
        drafts += generator.false_premise(article)
    pairs = reference_pairs(articles)
    for first, second in rng.sample(pairs, min(n_multi, len(pairs))):
        drafts += generator.multi(first, second)
    if n_oos:
        drafts += generator.out_of_scope(n_oos)
    return drafts


def append_candidates(drafts: Iterable[Draft], path: Path) -> list[Question]:
    """Add drafts as pending llm_candidate rows, skipping near-duplicates of existing ones."""
    questions = load_questions(path)
    seen = {normalise(q.question) for q in questions}
    added: list[Question] = []
    for draft in drafts:
        key = normalise(draft.question)
        if key in seen:
            continue
        seen.add(key)
        q = Question.model_validate(
            {
                "id": next_id([*questions, *added]),
                "question": draft.question,
                "gold_article_ids": draft.gold,
                "type": draft.type,
                "source": "llm_candidate",
                "status": "pending",
                "notes": draft.notes,
            }
        )
        added.append(q)
    save_questions([*questions, *added], path)
    return added


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m eurolex.evaluation.candidates")
    parser.add_argument("--model", help="defaults to CANDIDATE_MODEL")
    parser.add_argument("--articles", type=int, default=30, help="articles to sample")
    parser.add_argument("--per-article", type=int, default=2)
    parser.add_argument("--false-premise", type=int, default=5)
    parser.add_argument("--multi", type=int, default=10)
    parser.add_argument("--oos", type=int, default=15)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--questions", type=Path, default=QUESTIONS_PATH)
    parser.add_argument("--articles-file", type=Path, default=Path("data/processed/articles.jsonl"))
    parser.add_argument("--allow-same-model", action="store_true")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    logging.getLogger("httpx").setLevel(logging.WARNING)

    settings = get_settings()
    model = args.model or settings.candidate_model
    if not model:
        print("Set --model or CANDIDATE_MODEL.", file=sys.stderr)
        return 1
    if model == settings.llm_model and not args.allow_same_model:
        print(
            f"{model} is also the answering model (LLM_MODEL). Use a different model so the "
            "questions are not tuned to it, or pass --allow-same-model.",
            file=sys.stderr,
        )
        return 1
    llm = OllamaClient(settings.ollama_base_url, model, seed=args.seed, timeout_seconds=300)
    drafts = build_candidates(
        CandidateGenerator(llm),
        load_articles(args.articles_file),
        n_articles=args.articles,
        per_article=args.per_article,
        n_false_premise=args.false_premise,
        n_multi=args.multi,
        n_oos=args.oos,
        seed=args.seed,
    )
    added = append_candidates(drafts, args.questions)
    print(f"Added {len(added)} pending candidates to {args.questions}. Review them with:")
    print("  uv run python -m eurolex.evaluation.review_cli review")
    return 0


if __name__ == "__main__":
    sys.exit(main())
